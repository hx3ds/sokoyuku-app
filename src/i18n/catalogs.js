function pack(rows) {
    const jp = {};
    const hans = {};
    const hant = {};
    for (const [en, j, s, t] of rows) {
        jp[en] = j;
        hans[en] = s;
        hant[en] = t;
    }
    return { jp, 'zh-Hans': hans, 'zh-Hant': hant };
}

